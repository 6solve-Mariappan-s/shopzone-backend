import test, { after, before } from "node:test";
import assert from "node:assert/strict";
import { app } from "./app.js";
import { sequelize } from "./db.js";
let server;
let base;
before(async () => { server = app.listen(0, "127.0.0.1"); await new Promise((resolve) => server.once("listening", resolve)); base = `http://127.0.0.1:${server.address().port}`; });
after(async () => { await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve())); await sequelize.close(); });
test("Wishlist service health", async () => { const response = await fetch(`${base}/health`); assert.equal(response.status, 200); const payload = await response.json(); assert.equal(payload.service, "wishlist"); });
test("Wishlist data requires authentication", async () => { const response = await fetch(`${base}/api/wishlist`); assert.equal(response.status, 401); });